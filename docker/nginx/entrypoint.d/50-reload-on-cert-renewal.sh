#!/bin/sh
# certbot renew в соседнем контейнере обновит файлы на диске, но nginx держит
# сертификат в памяти и продолжит отдавать старый. --deploy-hook между
# контейнерами не дотянется, поэтому reload живёт здесь.
# Без этого автопродление формально работает, а через 90 дней сайт отдаёт
# истёкший сертификат, и узнаёшь об этом от пользователей.
#
# Скрипт обязан завершиться: /docker-entrypoint.sh выполняет их последовательно
# и только потом запускает nginx. Поэтому петля уходит в фон.
set -eu

(
    while :; do
        sleep 6h
        nginx -s reload 2>/dev/null || true
    done
) &

echo "$0: перезагрузка nginx запланирована каждые 6 часов"
