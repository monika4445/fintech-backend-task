from django.contrib.auth.models import AbstractUser
from django.db import models


class User(AbstractUser):
    """Пользователь с 64-битным первичным ключом.

    Зачем вообще своя модель, если штатной `django.contrib.auth.User` хватает по
    полям. Схема задания объявляет `User.id` как `bigint`, а штатная модель даёт
    `integer`: приложение `auth` переопределяет `DEFAULT_AUTO_FIELD` собственным
    `default_auto_field = AutoField`, и настройка проекта на него не влияет —
    его миграции историчны и Django их не меняет. Проверено на живой базе:
    `auth_user.id` приходил как `integer(32,0)`, а вместе с ним `integer`
    получали и обе колонки внешних ключей, `profile.user_id` и
    `transaction.user_id`, потому что колонка FK повторяет тип цели.

    Практический потолок 32-битного ключа — около 2.1 миллиарда записей, и для
    большинства систем этого достаточно. Но менять модель пользователя задним
    числом в Django болезненно, поэтому её и рекомендуют заводить в любом новом
    проекте сразу; здесь данных нет, и цена перехода нулевая.

    Полей у AbstractUser больше, чем в схеме задания: она перечисляет id,
    username и email, а сюда приходят ещё password, is_staff, date_joined и
    прочее. Это надмножество, а не расхождение: писать аутентификацию заново
    ради сокращения списка полей было бы плохим разменом.
    """

    id = models.BigAutoField(primary_key=True)

    class Meta(AbstractUser.Meta):
        # Имя таблицы как в схеме задания, рядом с profile и transaction.
        # `user` — зарезервированное слово в PostgreSQL, но Django всегда
        # заключает идентификаторы в кавычки, поэтому это безопасно.
        db_table = "user"
